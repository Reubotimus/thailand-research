import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:1080},acceptDownloads:true});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.TEST_URL||'http://127.0.0.1:3000');
 await page.getByRole('heading',{name:/Follow your/}).waitFor();
 await page.getByRole('button',{name:'Save Wat Arun to shortlist',exact:true}).click();
 await page.getByRole('button',{name:'Read about Wat Arun',exact:true}).click();
 const dialog=page.getByRole('dialog');await dialog.waitFor();
 assert.match(await dialog.innerText(),/200 THB|200 baht/i);
 await dialog.getByLabel(/Your trip notes/).fill('Pair with a river ferry at sunset.');
 await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
 await page.reload();
 await page.getByRole('button',{name:'Remove Wat Arun from shortlist',exact:true}).waitFor();
 await page.getByRole('button',{name:/My shortlist/}).click();
 assert.equal(await page.locator('.activity-card').count(),1);
 await page.getByRole('button',{name:'Read about Wat Arun',exact:true}).click();
 assert.equal(await page.getByRole('textbox',{name:/Your trip notes/}).inputValue(),'Pair with a river ferry at sunset.');
 await page.keyboard.press('Escape');
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export shortlist'}).click();
 assert.equal((await download).suggestedFilename(),'thailand-shortlist.md');
 await page.getByRole('button',{name:'Explore',exact:true}).click();
 await page.getByRole('searchbox').fill('no-result-impossible-1234');
 await page.getByRole('heading',{name:'No possibilities match just yet.'}).waitFor();
 await page.getByRole('button',{name:'Clear filters',exact:true}).last().click();
 const checks=page.locator('.compare-check input');await checks.nth(0).check();await checks.nth(1).check();
 await page.locator('.compare-tray').getByRole('button',{name:'Compare',exact:true}).click();
 await page.getByRole('dialog',{name:'Compare activities'}).waitFor();
 assert.ok(await page.getByRole('table').count());await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Clear comparison'}).click();
 await page.locator('.city-tabs').getByRole('button').nth(2).click();
 assert.ok((await page.locator('.city-badge').allTextContents()).every(x=>x==='Chiang Mai'));
 await page.getByRole('button',{name:'List view'}).click();assert.ok(await page.locator('.list-view').count());
 await page.getByRole('button',{name:'Grid view'}).click();
 await page.setViewportSize({width:390,height:844});await page.goto(process.env.TEST_URL||'http://127.0.0.1:3000');
 await page.getByRole('heading',{name:/Follow your/}).waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Mobile page overflows horizontally');
 await page.screenshot({path:'/tmp/thailand-mobile.png',fullPage:false});
 await page.locator('#explore').scrollIntoViewIfNeeded();await page.locator('.activity-card').first().scrollIntoViewIfNeeded();await page.waitForFunction(()=>{const img=document.querySelector('.visual-open img');return img&&img.complete&&img.naturalWidth>0;});await page.screenshot({path:'/tmp/thailand-mobile-registry.png'});
 await page.getByRole('button',{name:'Read about Wat Arun',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 assert.equal(await page.getByRole('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth),true,'Dialog overflows');
 await page.screenshot({path:'/tmp/thailand-mobile-detail.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: search, city filter, saved shortlist persistence, notes, export, comparison, view toggle, mobile overflow, dialog, and no browser errors.');
}finally{await browser.close();}
